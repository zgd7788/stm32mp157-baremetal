int main(void)
{
    int32_t status; /* EXTI initialization result. */

    status = HAL_EXTI9_Init();

    if (status == 0)
    {
        HAL_GIC_Init();
        HAL_CPU_EnableIrq();
    }

    for (;;)
    {
        if (status != 0)
        {
            /* Initialization failed; keep all interrupts disabled. */
        }
        else
        {
            __asm volatile ("wfi" ::: "memory");
        }
    }
}

